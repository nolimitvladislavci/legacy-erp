"""
synesis/script_builder.py

Generira Windows Python sync skriptu s potpunom izolacijom:
  - ORIGINAL  → nikad se ne diraju direktno (samo čitanje za backup)
  - BACKUP    → automatski backup prije svake operacije
  - WORK      → radna kopija za sav R/W rad
  - EXPORT    → JSON fajlovi koje ERP šalje natrag

Uvoz (Synesis → ERP):   Original → backup → work → čitaj → API
Izvoz (ERP → Synesis):  API export JSON → work → provjeri → zamijeni original
"""


def build_sync_script(cfg, company):
    """
    Generira kompletnu sync skriptu za Windows računalo.
    cfg  = SynesisConfig instance
    company = Company instance
    Vraća string s Python kodom.
    """
    slug = company.name.replace(" ", "_").replace(".", "").replace(",", "")[:20]
    connect_base = cfg.connect_base_path or r"C:\SynesisConnect"
    retention = cfg.backup_retention_days or 30

    L = []

    def a(line=""):
        L.append(line)

    # ── Header ─────────────────────────────────────────────────────────────
    a("#!/usr/bin/env python3")
    a("# -*- coding: utf-8 -*-")
    a('"""')
    a(f"synesis_sync.py — {company.name}")
    a(f"Generirano: {__import__('datetime').datetime.now().strftime('%d.%m.%Y %H:%M')}")
    a("")
    a("Instalacija: pip install pyodbc requests")
    a("Pokretanje:")
    a("  python synesis_sync.py              # sve (backup + uvoz + izvoz)")
    a("  python synesis_sync.py import       # samo uvoz Synesis → ERP")
    a("  python synesis_sync.py export       # samo izvoz ERP → Synesis")
    a("  python synesis_sync.py backup       # samo backup")
    a("  python synesis_sync.py status       # provjeri stanje")
    a('"""')
    a()
    a("import sys, os, shutil, json, datetime, decimal, time, hashlib, logging")
    a("import pyodbc, requests")
    a()

    # ── Konfiguracija ───────────────────────────────────────────────────────
    a("# =====================================================================")
    a("# KONFIGURACIJA — provjerite putanje")
    a("# =====================================================================")
    a()
    a("# Originalni Synesis fajlovi (SAMO ZA ČITANJE — nikad pisanje direktno)")
    a(f'STORAGE_ORIGINAL = r"{cfg.storage_db_path or r"C:\Synesis\FIRMA\Storage.mdb"}"')
    a(f'JOURNAL_ORIGINAL = r"{cfg.journal_db_path or r"C:\Synesis\FIRMA\Journal.mdb"}"')
    pos_db = cfg.pos_db_path or ""
    pos_pwd = cfg.pos_db_password or ""
    a(f'POS_ORIGINAL     = r"{pos_db}"')
    a(f'POS_PWD          = "{pos_pwd}"')
    a()
    a("# Connect radni folderi (automatski se kreiraju)")
    a(f'CONNECT_BASE     = r"{connect_base}"')
    a(f'FIRMA_SLUG       = "{slug}"')
    a("CONNECT_DIR      = os.path.join(CONNECT_BASE, FIRMA_SLUG)")
    a('BACKUP_DIR       = os.path.join(CONNECT_DIR, "backup")')
    a('WORK_DIR         = os.path.join(CONNECT_DIR, "work")')
    a('EXPORT_DIR       = os.path.join(CONNECT_DIR, "export")')
    a('LOG_FILE         = os.path.join(CONNECT_DIR, "connect_log.txt")')
    a()
    a("# Radne kopije (WORK — ovdje se čita i piše)")
    a('STORAGE_WORK     = os.path.join(WORK_DIR, "Storage_work.mdb")')
    a('JOURNAL_WORK     = os.path.join(WORK_DIR, "Journal_work.mdb")')
    a()
    a("# API")
    a('API_URL          = "https://limit-connect.com/api/synesis/import/"')
    a(f'API_TOKEN        = "{cfg.api_token}"')
    a(f'EXPORT_URL       = "https://limit-connect.com/api/synesis/export/{cfg.api_token}/"')
    a(f'CONFIRM_URL      = "https://limit-connect.com/api/synesis/export/{cfg.api_token}/confirm/"')
    a("BATCH_SIZE       = 200")
    a(f"BACKUP_KEEP_DAYS = {retention}")
    a()
    a('DRIVER = "Microsoft Access Driver (*.mdb, *.accdb)"')
    a()

    # ── Logger ──────────────────────────────────────────────────────────────
    a("# =====================================================================")
    a("# LOGGER")
    a("# =====================================================================")
    a()
    a("def setup_logger():")
    a("    os.makedirs(CONNECT_DIR, exist_ok=True)")
    a("    logging.basicConfig(")
    a("        level=logging.INFO,")
    a('        format="%(asctime)s [%(levelname)s] %(message)s",')
    a("        handlers=[")
    a('            logging.FileHandler(LOG_FILE, encoding="utf-8"),')
    a("            logging.StreamHandler(sys.stdout),")
    a("        ]")
    a("    )")
    a('    return logging.getLogger("synesis_connect")')
    a()
    a("log = setup_logger()")
    a()

    # ── Helper funkcije ─────────────────────────────────────────────────────
    a("# =====================================================================")
    a("# HELPER FUNKCIJE")
    a("# =====================================================================")
    a()
    a("def json_serial(o):")
    a('    if isinstance(o, datetime.datetime): return o.strftime("%Y-%m-%d %H:%M:%S")')
    a('    if isinstance(o, datetime.date):     return o.strftime("%Y-%m-%d")')
    a("    if isinstance(o, decimal.Decimal):   return float(o)")
    a("    return str(o)")
    a()
    a("def safe(v):")
    a("    if v is None: return None")
    a("    if isinstance(v, float) and v == int(v): return int(v)")
    a("    s = str(v).strip()")
    a("    return s if s else None")
    a()
    a("def file_hash(path):")
    a('    """SHA256 fajla za provjeru integriteta."""')
    a("    h = hashlib.sha256()")
    a('    with open(path, "rb") as f:')
    a('        for chunk in iter(lambda: f.read(8192), b""): h.update(chunk)')
    a("    return h.hexdigest()")
    a()
    a("def ensure_dirs():")
    a('    """Kreiraj sve potrebne foldere."""')
    a("    for d in [CONNECT_DIR, BACKUP_DIR, WORK_DIR, EXPORT_DIR]:")
    a("        os.makedirs(d, exist_ok=True)")
    a('    log.info(f"Connect folder: {CONNECT_DIR}")')
    a()
    a("def send_batch(sync_type, data):")
    a('    headers = {"Content-Type": "application/json", "Authorization": f"Token {API_TOKEN}"}')
    a('    payload = json.dumps({"type": sync_type, "data": data}, default=json_serial, ensure_ascii=False)')
    a("    try:")
    a('        r = requests.post(API_URL, data=payload.encode("utf-8"), headers=headers, timeout=120)')
    a("        return r.json()")
    a("    except Exception as e:")
    a('        log.error(f"API greška ({sync_type}): {e}")')
    a('        return {"error": str(e)}')
    a()

    # ── KORAK 1: BACKUP ─────────────────────────────────────────────────────
    a("# =====================================================================")
    a("# KORAK 1 — BACKUP (uvijek prvi, nikad preskačemo)")
    a("# =====================================================================")
    a()
    a('def make_backup(db_path, label="Storage"):')
    a('    """')
    a("    Kreira timestamped backup originalnog MDB fajla.")
    a("    Vraća putanju backupa ili None ako nije uspio.")
    a("    VAŽNO: Ako backup ne uspije, cijeli sync se zaustavlja.")
    a('    """')
    a("    if not os.path.exists(db_path):")
    a('        log.warning(f"  Original ne postoji, preskačem backup: {db_path}")')
    a("        return None")
    a('    ts  = datetime.datetime.now().strftime("%Y-%m-%d_%H-%M")')
    a('    dst = os.path.join(BACKUP_DIR, f"{label}_{ts}.mdb")')
    a("    try:")
    a("        shutil.copy2(db_path, dst)")
    a("        h = file_hash(dst)")
    a("        # Spremi hash uz backup")
    a('        with open(dst + ".sha256", "w") as f: f.write(h)')
    a('        log.info(f"  ✅ Backup: {dst}")')
    a('        log.info(f"  🔑 SHA256: {h[:16]}...")')
    a("        return dst")
    a("    except Exception as e:")
    a('        log.error(f"  ❌ Backup NIJE uspio: {e}")')
    a("        return None")
    a()
    a("def cleanup_old_backups():")
    a('    """Briše backupe starije od BACKUP_KEEP_DAYS dana."""')
    a("    cutoff = datetime.datetime.now() - datetime.timedelta(days=BACKUP_KEEP_DAYS)")
    a("    removed = 0")
    a("    for f in os.listdir(BACKUP_DIR):")
    a("        fpath = os.path.join(BACKUP_DIR, f)")
    a("        if os.path.isfile(fpath):")
    a("            mtime = datetime.datetime.fromtimestamp(os.path.getmtime(fpath))")
    a("            if mtime < cutoff:")
    a("                os.remove(fpath)")
    a("                removed += 1")
    a('    if removed: log.info(f"  🗑️  Obrisano starih backupa: {removed}")')
    a()
    a("def do_backup():")
    a('    """Napravi backup svih MDB fajlova."""')
    a('    log.info("\\n=== BACKUP ===")')
    a("    results = {}")
    a('    results["storage"] = make_backup(STORAGE_ORIGINAL, "Storage")')
    a('    results["journal"] = make_backup(JOURNAL_ORIGINAL, "Journal")')
    a("    if POS_ORIGINAL:")
    a('        results["pos"] = make_backup(POS_ORIGINAL, "POS")')
    a("    # Ako Storage backup nije uspio — STOP")
    a('    if results["storage"] is None and os.path.exists(STORAGE_ORIGINAL):')
    a('        log.error("  ❌ KRITIČNO: Storage backup nije uspio. Sync prekinut.")')
    a("        sys.exit(1)")
    a("    cleanup_old_backups()")
    a("    return results")
    a()

    # ── KORAK 2: RADNA KOPIJA ───────────────────────────────────────────────
    a("# =====================================================================")
    a("# KORAK 2 — RADNA KOPIJA (sav R/W rad ovdje)")
    a("# =====================================================================")
    a()
    a("def make_work_copy():")
    a('    """Kopira originale u WORK folder. Sve operacije idu na work kopije."""')
    a('    log.info("\\n=== KREIRANJE RADNE KOPIJE ===")')
    a("    if os.path.exists(STORAGE_ORIGINAL):")
    a("        shutil.copy2(STORAGE_ORIGINAL, STORAGE_WORK)")
    a('        log.info(f"  ✅ Storage work kopija: {STORAGE_WORK}")')
    a("    if os.path.exists(JOURNAL_ORIGINAL):")
    a("        shutil.copy2(JOURNAL_ORIGINAL, JOURNAL_WORK)")
    a('        log.info(f"  ✅ Journal work kopija: {JOURNAL_WORK}")')
    a()
    a("def conn_storage():")
    a('    """Otvori konekciju na WORK kopiju Storage.mdb."""')
    a('    return pyodbc.connect(f"DRIVER={{{DRIVER}}};DBQ={STORAGE_WORK};")')
    a()
    a("def conn_journal():")
    a('    """Otvori konekciju na WORK kopiju Journal.mdb."""')
    a('    return pyodbc.connect(f"DRIVER={{{DRIVER}}};DBQ={JOURNAL_WORK};")')
    a()

    # ── KORAK 3: UVOZ Synesis → ERP ─────────────────────────────────────────
    a("# =====================================================================")
    a("# KORAK 3 — UVOZ (Synesis → ERP)")
    a("# =====================================================================")
    a()
    a("def import_partners():")
    a('    log.info("\\n--- PARTNERI: Synesis → ERP ---")')
    a("    conn = conn_storage()")
    a("    cur  = conn.cursor()")
    a('    cur.execute("""')
    a("        SELECT PARTNER_ID, PARTNER_NAME, PARTNER_VATNUMBER, PARTNER_STREET,")
    a("               CITY_NAME, CITY_ZIPCODE, PARTNER_EMAIL, PARTNER_PHONE,")
    a("               PARTNER_MOBILE, PARTNER_WEB, INT_COUNTRYID,")
    a("               PARTNER_DISCOUNTRATE, PARTNER_PAYMENTDAYS, PARTNER_TYPE")
    a("        FROM PARTNERS WHERE PARTNER_NAME IS NOT NULL ORDER BY PARTNER_ID")
    a('    """)')
    a("    cols = [d[0] for d in cur.description]")
    a("    rows = [dict(zip(cols, [safe(v) for v in row])) for row in cur.fetchall()]")
    a("    conn.close()")
    a('    log.info(f"  Pronađeno partnera: {len(rows)}")')
    a("    c = u = e = 0")
    a("    for i in range(0, len(rows), BATCH_SIZE):")
    a('        res = send_batch("partners", rows[i:i+BATCH_SIZE])')
    a('        c += res.get("created", 0); u += res.get("updated", 0); e += res.get("errors", 0)')
    a('    log.info(f"  ✅ Kreirano: {c} | Ažurirano: {u} | Greške: {e}")')
    a()
    a("def import_items():")
    a('    log.info("\\n--- ARTIKLI: Synesis → ERP ---")')
    a("    conn = conn_storage()")
    a("    cur  = conn.cursor()")
    a('    cur.execute("""')
    a("        SELECT ITEM_ID, ITEM_NAME, ITEM_MEASURE, ITEM_BARCODE,")
    a("               ITEM_NETPRICE, VAT_RATE, ITEM_PRICE,")
    a("               ITEMGROUP_NAME, ITEM_TYPE, NKPID, ITEM_REMARK")
    a("        FROM ITEMS WHERE ITEM_NAME IS NOT NULL ORDER BY ITEM_ID")
    a('    """)')
    a("    cols = [d[0] for d in cur.description]")
    a("    rows = [dict(zip(cols, [safe(v) for v in row])) for row in cur.fetchall()]")
    a("    conn.close()")
    a('    log.info(f"  Pronađeno artikala: {len(rows)}")')
    a("    c = u = e = 0")
    a("    for i in range(0, len(rows), BATCH_SIZE):")
    a('        res = send_batch("items", rows[i:i+BATCH_SIZE])')
    a('        c += res.get("created", 0); u += res.get("updated", 0); e += res.get("errors", 0)')
    a('    log.info(f"  ✅ Kreirano: {c} | Ažurirano: {u} | Greške: {e}")')
    a()
    a("def import_invoices(year=None):")
    a('    """Uvoz faktura iz Journal.mdb za određenu godinu (ili sve)."""')
    a('    label = f"godinu {year}" if year else "sve godine"')
    a('    log.info(f"\\n--- FAKTURE ({label}): Synesis → ERP ---")')
    a("    if not os.path.exists(JOURNAL_WORK):")
    a('        log.warning("  Journal.mdb nije dostupan, preskačem fakture.")')
    a("        return")
    a("    conn = conn_journal()")
    a("    cur  = conn.cursor()")
    a('    year_filter = f"AND YEAR(INVOICE_DATE) = {year}" if year else ""')
    a("    try:")
    a('        cur.execute(f"""')
    a("            SELECT INVOICE_ID, INVOICE_NUMBER, INVOICE_DATE,")
    a("                   PARTNER_ID, PARTNER_NAME,")
    a("                   SUBTOTAL, VAT_AMOUNT, TOTAL,")
    a("                   PAYMENT_TYPE, ZKI, JIR,")
    a("                   FISCAL_DATETIME, IS_FISCALIZED")
    a("            FROM INVOICES")
    a("            WHERE INVOICE_ID IS NOT NULL {year_filter}")
    a("            ORDER BY INVOICE_DATE")
    a('        """)')
    a("    except Exception as ex:")
    a('        log.warning(f"  Tablica INVOICES nije dostupna: {ex}")')
    a("        conn.close(); return")
    a("    cols = [d[0] for d in cur.description]")
    a("    rows = [dict(zip(cols, [safe(v) for v in row])) for row in cur.fetchall()]")
    a("    conn.close()")
    a('    log.info(f"  Pronađeno faktura: {len(rows)}")')
    a("    if not rows: return")
    a('    payload = {"year": year, "invoices": rows}')
    a('    res = send_batch("invoices", payload)')
    a('    log.info(f"  ✅ Uvezeno: {res.get("created",0)} | Preskočeno (duplikat): {res.get("skipped",0)}")')
    a()
    a("def import_pos():")
    a('    """Uvoz POS kase."""')
    a("    if not POS_ORIGINAL: return")
    a('    log.info("\\n--- POS KASA: Synesis → ERP ---")')
    a('    pos_work = os.path.join(WORK_DIR, "POS_work.mdb")')
    a("    shutil.copy2(POS_ORIGINAL, pos_work)")
    a("    if POS_PWD:")
    a('        cs = f"DRIVER={{{DRIVER}}};DBQ={pos_work};PWD={POS_PWD};"')
    a("    else:")
    a('        cs = f"DRIVER={{{DRIVER}}};DBQ={pos_work};"')
    a("    conn = pyodbc.connect(cs)")
    a("    cur  = conn.cursor()")
    a('    cutoff = (datetime.datetime.now() - datetime.timedelta(days=90)).strftime("%Y-%m-%d")')
    a("    rows = []")
    a("    try:")
    a("        cur.execute(")
    a('            "SELECT Receipt_ID, Receipt_Date, Receipt_Ammount, Receipt_VATAmmout,"')
    a('            " Receipt_PaymentType, Receipt_ZKI, Receipt_JIR, Receipt_Customer"')
    a('            " FROM Receipts WHERE Receipt_Date >= ? ORDER BY Receipt_Date", cutoff)')
    a("        cols = [d[0] for d in cur.description]")
    a("        rows = [dict(zip(cols, [safe(v) for v in r])) for r in cur.fetchall()]")
    a("    except Exception as ex:")
    a('        log.warning(f"  POS upozorenje: {ex}")')
    a("    conn.close()")
    a("    os.remove(pos_work)")
    a('    log.info(f"  Pronađeno POS bonova: {len(rows)}")')
    a("    if rows:")
    a('        res = send_batch("pos", {"receipts": rows})')
    a('        log.info(f"  ✅ POS sinkronizirano")')
    a()

    # ── KORAK 4: IZVOZ ERP → Synesis ────────────────────────────────────────
    a("# =====================================================================")
    a("# KORAK 4 — IZVOZ (ERP → Synesis)")
    a("# =====================================================================")
    a()
    a("def fetch_export_queue():")
    a('    """Preuzmi red čekanja za izvoz s ERP-a."""')
    a('    log.info("\\n--- PROVJERA ERP EXPORT QUEUE ---")')
    a("    try:")
    a("        r = requests.get(EXPORT_URL, timeout=30)")
    a("        data = r.json()")
    a('        items    = data.get("items", [])')
    a('        partners = data.get("partners", [])')
    a("        total = len(items) + len(partners)")
    a('        log.info(f"  ERP export: {len(items)} artikala, {len(partners)} partnera")')
    a("        # Spremi lokalno kao JSON")
    a('        ts = datetime.datetime.now().strftime("%Y-%m-%d_%H-%M")')
    a('        with open(os.path.join(EXPORT_DIR, f"export_{ts}.json"), "w", encoding="utf-8") as f:')
    a("            json.dump(data, f, default=json_serial, ensure_ascii=False, indent=2)")
    a("        return data")
    a("    except Exception as e:")
    a('        log.error(f"  Greška pri dohvatu export queue: {e}")')
    a('        return {"items": [], "partners": []}')
    a()
    a("def apply_export_to_work(export_data):")
    a('    """')
    a("    Upiši ERP promjene u WORK kopiju Storage.mdb.")
    a("    Nikad ne pišemo u original — samo u work kopiju.")
    a('    """')
    a('    items    = export_data.get("items", [])')
    a('    partners = export_data.get("partners", [])')
    a("    if not items and not partners:")
    a('        log.info("  Nema podataka za izvoz.")')
    a("        return True")
    a('    log.info(f"\\n--- PISANJE U WORK KOPIJU ---")')
    a("    conn = conn_storage()")
    a("    cur  = conn.cursor()")
    a("    ok = errors = 0")
    a("    # Artikli")
    a("    for item in items:")
    a("        try:")
    a('            action = item.get("action", "update")')
    a('            fields = item.get("fields", {})')
    a('            synesis_id = item.get("synesis_id", "")')
    a('            if action == "update" and synesis_id:')
    a('                sets = ", ".join(f"{k}=?" for k in fields)')
    a("                vals = list(fields.values()) + [synesis_id]")
    a('                cur.execute(f"UPDATE ITEMS SET {sets} WHERE ITEM_ID=?", vals)')
    a('            elif action == "insert":')
    a('                cols = ", ".join(fields.keys())')
    a('                placeholders = ", ".join("?" * len(fields))')
    a('                cur.execute(f"INSERT INTO ITEMS ({cols}) VALUES ({placeholders})", list(fields.values()))')
    a("            ok += 1")
    a("        except Exception as e:")
    a('            log.warning(f"  Artikl greška: {e}")')
    a("            errors += 1")
    a("    # Partneri")
    a("    for partner in partners:")
    a("        try:")
    a('            action = partner.get("action", "update")')
    a('            fields = partner.get("fields", {})')
    a('            synesis_id = partner.get("synesis_id", "")')
    a('            if action == "update" and synesis_id:')
    a('                sets = ", ".join(f"{k}=?" for k in fields)')
    a("                vals = list(fields.values()) + [synesis_id]")
    a('                cur.execute(f"UPDATE PARTNERS SET {sets} WHERE PARTNER_ID=?", vals)')
    a('            elif action == "insert":')
    a('                cols = ", ".join(fields.keys())')
    a('                placeholders = ", ".join("?" * len(fields))')
    a('                cur.execute(f"INSERT INTO PARTNERS ({cols}) VALUES ({placeholders})", list(fields.values()))')
    a("            ok += 1")
    a("        except Exception as e:")
    a('            log.warning(f"  Partner greška: {e}")')
    a("            errors += 1")
    a("    conn.commit()")
    a("    conn.close()")
    a('    log.info(f"  Upisano u work: {ok} | Greške: {errors}")')
    a("    return errors == 0")
    a()
    a("def apply_work_to_original():")
    a('    """')
    a("    ZADNJI KORAK — zamijeni original work kopijom.")
    a("    Samo ako je sve prošlo OK.")
    a("    VAŽNO: Čuva stari original kao emergency backup.")
    a('    """')
    a('    log.info("\\n--- PRIMJENA NA ORIGINAL ---")')
    a('    emergency = STORAGE_WORK + ".emergency_backup"')
    a("    try:")
    a("        # Emergency backup originala")
    a("        shutil.copy2(STORAGE_ORIGINAL, emergency)")
    a("        # Zamjena")
    a("        shutil.copy2(STORAGE_WORK, STORAGE_ORIGINAL)")
    a("        # Provjeri da je original ok")
    a('        conn = pyodbc.connect(f"DRIVER={{{DRIVER}}};DBQ={STORAGE_ORIGINAL};")')
    a('        conn.cursor().execute("SELECT COUNT(*) FROM ITEMS")')
    a("        conn.close()")
    a("        # Sve ok — obriši emergency")
    a("        os.remove(emergency)")
    a('        log.info("  ✅ Original uspješno ažuriran.")')
    a("        return True")
    a("    except Exception as e:")
    a('        log.error(f"  ❌ KRITIČNO: Zamjena originala nije uspjela: {e}")')
    a("        # Pokušaj restauraciju")
    a("        if os.path.exists(emergency):")
    a("            try:")
    a("                shutil.copy2(emergency, STORAGE_ORIGINAL)")
    a('                log.info("  ✅ Original restauriran iz emergency backupa.")')
    a("            except Exception as e2:")
    a('                log.error(f"  ❌ ❌ Restauracija nije uspjela: {e2}")')
    a('                log.error(f"     RUČNO kopiraj: {emergency} → {STORAGE_ORIGINAL}")')
    a("        return False")
    a()
    a("def confirm_export():")
    a('    """Potvrdi ERP-u da je izvoz primjenjen."""')
