/* ═══════════════════════════════════════════════════════════════
   ENGINE — Language switching
   ═══════════════════════════════════════════════════════════════ */

(function() {
    "use strict";

    // Detect saved language or browser language
    function detectLanguage() {
        var saved = localStorage.getItem('nl-lang');
        if (saved && NL_TRANSLATIONS[saved]) return saved;
        var nav = (navigator.language || navigator.userLanguage || 'hr').substring(0, 2).toLowerCase();
        return NL_TRANSLATIONS[nav] ? nav : 'hr';
    }

    // Apply translations to all elements with data-i18n attribute
    function applyTranslations(lang) {
        var t = NL_TRANSLATIONS[lang];
        if (!t) return;
        document.querySelectorAll('[data-i18n]').forEach(function(el) {
            var key = el.getAttribute('data-i18n');
            if (t[key]) {
                if (el.tagName === 'INPUT' && el.type !== 'submit') {
                    el.placeholder = t[key];
                } else {
                    el.textContent = t[key];
                }
            }
        });
        // Update html lang attribute
        document.documentElement.lang = lang;
        // Save preference
        localStorage.setItem('nl-lang', lang);
        // Update selector if exists
        var sel = document.getElementById('nl-lang-selector');
        if (sel) sel.value = lang;
    }

    // Theme toggle
    function toggleTheme() {
        var html = document.documentElement;
        var current = html.getAttribute('data-theme');
        var next = current === 'light' ? 'dark' : 'light';
        html.setAttribute('data-theme', next);
        localStorage.setItem('nl-theme', next);
        // Update icon
        var btn = document.getElementById('nl-theme-btn');
        if (btn) btn.innerHTML = next === 'light'
            ? '<i class="fas fa-moon"></i>'
            : '<i class="fas fa-sun"></i>';
    }

    // Init theme from storage
    function initTheme() {
        var saved = localStorage.getItem('nl-theme') || 'dark';
        document.documentElement.setAttribute('data-theme', saved);
        var btn = document.getElementById('nl-theme-btn');
        if (btn) btn.innerHTML = saved === 'light'
            ? '<i class="fas fa-moon"></i>'
            : '<i class="fas fa-sun"></i>';
    }

    // Expose globals
    window.nlSwitchLang = function(lang) { applyTranslations(lang); };
    window.nlToggleTheme = toggleTheme;

    // Auto-init on DOM ready
    document.addEventListener('DOMContentLoaded', function() {
        initTheme();
        var lang = detectLanguage();
        applyTranslations(lang);

        // Bind language selector
        var sel = document.getElementById('nl-lang-selector');
        if (sel) {
            sel.value = lang;
            sel.addEventListener('change', function() {
                applyTranslations(this.value);
            });
        }

        // Bind theme toggle
        var btn = document.getElementById('nl-theme-btn');
        if (btn) btn.addEventListener('click', toggleTheme);
    });
})();
