def get_bilingual_labels(primary_lang, secondary_lang, doctype="R"):
    """Return a dict with 'primary' and 'secondary' label sets, with doc_title resolved."""
    p = dict(LABELS.get(primary_lang, LABELS["hr"]))
    s = dict(LABELS.get(secondary_lang, LABELS["de"]))
    p["doc_title"] = p["doc_title_map"].get(doctype, p["doc_title_default"])
    s["doc_title"] = s["doc_title_map"].get(doctype, s["doc_title_default"])
    del p["doc_title_map"], p["doc_title_default"]
    del s["doc_title_map"], s["doc_title_default"]
    return {"primary": p, "secondary": s}
